"""Build the Physics Lab catalog from simulation folders (manifest v2).

Every rule here is documented in PUBLISHING.md section 3-5 and 10.
Any violation stops the deploy; error messages tell the publisher what to fix.
Do not edit this file when publishing an animation.
"""
import datetime
import hashlib
import json
import re
import struct
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATEGORIES = ["mechanics", "thermal", "waves", "electromagnetism", "optics", "modern", "experiments"]
TINTS = {"navy", "teal", "ochre", "plum", "rose", "slate"}
DEVICES = {"ipad-landscape", "desktop", "phone-landscape", "phone-portrait"}
STATUSES = {"published", "hidden"}
SLUG_RE = re.compile(r"[a-z0-9]+(?:-[a-z0-9]+)*")
REQUIRED = {"manifestVersion", "title", "category", "description", "keywords", "highlights",
            "howto", "model", "devices", "tint", "status", "updated"}
OPTIONAL = {"subtitle"}

SVG_NS = "{http://www.w3.org/2000/svg}"
SVG_TAGS = {"svg", "g", "path", "circle", "ellipse", "rect", "line", "polyline", "polygon"}
SVG_MAX_BYTES = 4096
PALETTE = {"#1c1b18", "#1f3a68", "#6f8fc4", "#2f9c90", "#8a6ad6", "#a65f00",
           "#ec9730", "#bd5b84", "#8a8170", "#fffdf8"}
COVER_SIZE = (1600, 900)
COVER_MAX_BYTES = 300 * 1024


class CatalogError(Exception):
    def __init__(self, errors):
        super().__init__("\n".join(errors))
        self.errors = errors


def text_ok(value, low, high):
    return isinstance(value, str) and value == value.strip() and low <= len(value) <= high


def check_manifest(obj, category, where, errors):
    def err(msg):
        errors.append(f"{where}: {msg}")

    if not isinstance(obj, dict):
        err("manifest 必須是 JSON 物件")
        return
    missing = REQUIRED - set(obj)
    extra = set(obj) - REQUIRED - OPTIONAL
    if missing:
        err(f"缺少必要欄位 {sorted(missing)}")
    if extra:
        err(f"不允許的欄位 {sorted(extra)}（網址由系統計算，不可寫 path）")
    if "【請填" in json.dumps(obj, ensure_ascii=False) or "【選填" in json.dumps(obj, ensure_ascii=False):
        err("仍有範本的【請填】／【選填】文字，請改成這支動畫的實際內容")
    if obj.get("manifestVersion") != 2:
        err("manifestVersion 必須是 2")
    title = obj.get("title")
    if not text_ok(title, 2, 20) or "｜" in str(title):
        err("title 須為 2～20 字且不含「｜」，副標請寫在 subtitle")
    if "subtitle" in obj and not text_ok(obj["subtitle"], 2, 20):
        err("subtitle 須為 2～20 字")
    if obj.get("category") != category:
        err(f"category 必須與資料夾相同（{category}）")
    if not text_ok(obj.get("description"), 30, 120):
        err("description 須為 30～120 字")
    kws = obj.get("keywords")
    if not (isinstance(kws, list) and 3 <= len(kws) <= 12 and all(text_ok(k, 1, 12) for k in kws)
            and len(set(kws)) == len(kws)):
        err("keywords 須為 3～12 個不重複的詞，每個 1～12 字")
    hls = obj.get("highlights")
    if not (isinstance(hls, list) and 3 <= len(hls) <= 5 and all(text_ok(h, 15, 60) for h in hls)):
        err("highlights 須為 3～5 條，每條 15～60 字")
    if not text_ok(obj.get("howto"), 30, 150):
        err("howto 須為 30～150 字")
    if not text_ok(obj.get("model"), 30, 200):
        err("model 須為 30～200 字")
    devices = obj.get("devices")
    if not (isinstance(devices, list) and devices and len(set(devices)) == len(devices)
            and set(devices) <= DEVICES and "ipad-landscape" in devices):
        err(f"devices 須從 {sorted(DEVICES)} 選擇、不重複，且必須包含 ipad-landscape")
    if obj.get("tint") not in TINTS:
        err(f"tint 須為 {sorted(TINTS)} 其中之一")
    if obj.get("status") not in STATUSES:
        err("status 須為 published 或 hidden")
    updated = obj.get("updated")
    try:
        if not (isinstance(updated, str) and re.fullmatch(r"\d{4}-\d{2}-\d{2}", updated)):
            raise ValueError
        datetime.date.fromisoformat(updated)
    except ValueError:
        err("updated 須為 YYYY-MM-DD 的有效日期")


def check_icon(path, where, errors):
    def err(msg):
        errors.append(f"{where}/icon.svg: {msg}")

    raw = path.read_bytes()
    if len(raw) > SVG_MAX_BYTES:
        err(f"檔案超過 {SVG_MAX_BYTES} bytes")
    if b"<!DOCTYPE" in raw.upper() or b"<!ENTITY" in raw.upper():
        err("不可包含 DOCTYPE 或 ENTITY")
        return None
    try:
        root = ET.fromstring(raw)
    except ET.ParseError as exc:
        err(f"不是合法的 SVG/XML（{exc}）")
        return None
    if root.tag != SVG_NS + "svg":
        err('根元素必須是 <svg xmlns="http://www.w3.org/2000/svg">')
        return None
    if root.get("viewBox") != "0 0 72 72":
        err('viewBox 必須是 "0 0 72 72"')
    strokes = set()

    def walk(node, inherited_stroke, inherited_width):
        tag = node.tag.replace(SVG_NS, "")
        if tag not in SVG_TAGS:
            err(f"不允許的元素 <{tag}>")
            return
        stroke, width = inherited_stroke, inherited_width
        for name, value in node.attrib.items():
            local = name.split("}")[-1]
            if local.startswith("on") or local in {"href", "style", "class", "filter", "mask", "clip-path"}:
                err(f"<{tag}> 不允許的屬性 {local}")
            if local in {"fill", "stroke"} and value != "none" and value.lower() not in PALETTE:
                err(f"<{tag}> 的 {local}={value} 不在色票內")
        if node.get("stroke"):
            stroke = node.get("stroke").lower()
        if node.get("stroke-width"):
            try:
                width = float(node.get("stroke-width"))
            except ValueError:
                err(f"<{tag}> 的 stroke-width 不是數字")
                width = 0.0
            if not 2 <= width <= 5:
                err(f"<{tag}> 的 stroke-width={node.get('stroke-width')} 須介於 2～5")
        if tag not in {"svg", "g"} and stroke and stroke != "none":
            strokes.add(stroke)
            if width is None:
                err(f"<{tag}> 有線條但未設定 stroke-width（2～5）")
        for child in node:
            walk(child, stroke, width)

    walk(root, None, None)
    if len(strokes) > 3:
        err(f"線條顏色 {len(strokes)} 種，最多 3 種")
    return hashlib.sha256(re.sub(rb"\s+", b"", raw)).hexdigest()


def webp_size(raw):
    if len(raw) < 30 or raw[:4] != b"RIFF" or raw[8:12] != b"WEBP":
        return None
    chunk = raw[12:16]
    if chunk == b"VP8 ":
        w, h = struct.unpack("<HH", raw[26:30])
        return w & 0x3FFF, h & 0x3FFF
    if chunk == b"VP8L":
        b = raw[21:25]
        return 1 + (((b[1] & 0x3F) << 8) | b[0]), 1 + (((b[3] & 0x0F) << 10) | (b[2] << 2) | ((b[1] & 0xC0) >> 6))
    if chunk == b"VP8X":
        return 1 + int.from_bytes(raw[24:27], "little"), 1 + int.from_bytes(raw[27:30], "little")
    return None


def build(root=ROOT):
    errors = []
    sims = root / "simulations"
    for entry in sorted(sims.glob("*/*/index.html")):
        if not (entry.parent / "manifest.json").is_file():
            errors.append(f"{entry.parent.relative_to(root).as_posix()}: 缺少 manifest.json")
    catalog, icon_hashes = [], {}
    template_icon = root / "docs" / "templates" / "icon.svg"
    if template_icon.is_file():
        icon_hashes[hashlib.sha256(re.sub(rb"\s+", b"", template_icon.read_bytes())).hexdigest()] = "docs/templates（範本）"
    for file in sorted(sims.rglob("manifest.json")):
        rel = file.relative_to(root)
        where = rel.parent.as_posix()
        if len(rel.parts) != 4:
            errors.append(f"{rel.as_posix()}: 位置錯誤，必須是 simulations/<category>/<slug>/manifest.json")
            continue
        category, slug = rel.parts[1], rel.parts[2]
        if category not in CATEGORIES:
            errors.append(f"{where}: 分類 {category} 不存在，只能是 {CATEGORIES}")
            continue
        if not SLUG_RE.fullmatch(slug):
            errors.append(f"{where}: slug 只能用小寫英文、數字與連字號")
            continue
        folder = file.parent
        if not (folder / "index.html").is_file():
            errors.append(f"{where}: 缺少 index.html")
        if not any(folder.glob("TEST_REPORT*.md")):
            errors.append(f"{where}: 缺少 TEST_REPORT.md")
        try:
            obj = json.loads(file.read_text(encoding="utf-8"))
        except (json.JSONDecodeError, UnicodeDecodeError) as exc:
            errors.append(f"{where}/manifest.json: 不是合法的 UTF-8 JSON（{exc}）")
            continue
        check_manifest(obj, category, f"{where}/manifest.json", errors)
        icon = folder / "icon.svg"
        if not icon.is_file():
            errors.append(f"{where}: 缺少 icon.svg")
        else:
            digest = check_icon(icon, where, errors)
            if digest and digest in icon_hashes:
                errors.append(f"{where}/icon.svg: 與 {icon_hashes[digest]} 的圖示完全相同，請畫出這支動畫的專屬現象")
            elif digest:
                icon_hashes[digest] = where
        cover = folder / "cover.webp"
        has_cover = cover.is_file()
        if has_cover:
            raw = cover.read_bytes()
            if len(raw) > COVER_MAX_BYTES:
                errors.append(f"{where}/cover.webp: 超過 300 KB")
            if webp_size(raw) != COVER_SIZE:
                errors.append(f"{where}/cover.webp: 必須是 1600×900 的 WebP")
        if isinstance(obj, dict) and obj.get("status") == "published":
            path = f"simulations/{category}/{slug}/"
            item = {k: obj[k] for k in ("title", "subtitle", "category", "description", "keywords",
                                        "highlights", "howto", "model", "devices", "tint", "updated") if k in obj}
            item.update(path=path, icon=path + "icon.svg", cover=path + "cover.webp" if has_cover else None)
            catalog.append(item)
    if errors:
        raise CatalogError(errors)
    return catalog


def main():
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8")
    try:
        catalog = build(ROOT)
    except CatalogError as exc:
        print(f"上架檢查未通過（{len(exc.errors)} 項），網站不會更新：", file=sys.stderr)
        for line in exc.errors:
            print(f"  - {line}", file=sys.stderr)
        print("規則見 PUBLISHING.md；請修正動畫資料夾內的檔案，不要修改本程式。", file=sys.stderr)
        sys.exit(1)
    (ROOT / "simulations.json").write_text(json.dumps(catalog, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Catalog generated: {len(catalog)} animations")


if __name__ == "__main__":
    main()
